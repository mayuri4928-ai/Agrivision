export function getLocalizedCropName(cropId: string, lang: LanguageCode): string {
  const norm = cropId.toLowerCase().trim();
  const crop = LOCALIZED_CROP_NAMES[norm];
  if (crop && crop[lang]) {
    return crop[lang];
  }
  // Search partial matches
  for (const key of Object.keys(LOCALIZED_CROP_NAMES)) {
    if (norm.includes(key) || key.includes(norm)) {
      return LOCALIZED_CROP_NAMES[key][lang] || LOCALIZED_CROP_NAMES[key].en;
    }
  }
  return cropId;
}

