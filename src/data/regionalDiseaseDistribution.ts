/**
 * Returns disease prevalence for a specific zone and disease
 */
export function getZoneDiseasePrevalence(zoneId: string, className: string) {
  const zone = AGRO_CLIMATIC_ZONES.find((z) => z.id === zoneId);
  if (!zone) return null;
  return zone.diseasePrevalences[className] || null;
}
